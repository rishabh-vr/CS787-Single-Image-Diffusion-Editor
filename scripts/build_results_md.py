"""Stitch reports/tables/*.md, reports/failure/*.json and reports/figures/** into docs/results.md.
Rerun after every analysis. Sections appear only for results that exist, and each carries its provenance
(so a preliminary laptop-pilot table can never be mistaken for a final Colab result)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
T, FAIL, FIG = ROOT / "reports" / "tables", ROOT / "reports" / "failure", ROOT / "reports" / "figures"

SECTIONS = [
    ("track1_table1", "Track 1 — reproduction (Colab T4, official code, fp32)", "final"),
    ("track1_near_duplicates", "Track 1 — near-duplicate rate", "final"),
    ("track2_setA_by_category", "Track 2 — Set A by category (Colab T4)", "final"),
    ("track2_vs_natural", "Track 2 — OOD vs natural reference", "final"),
    ("track2_setB_factor_effects", "Track 2 — Set B factor effects (Colab T4, 128 px)", "final"),
    ("track2_setA_descriptor_correlations", "Track 2 — descriptor correlations", "final"),
    ("phase9_ablation_deltas", "Ablations (Colab T4)", "final"),
    ("track3_methods", "Track 3 — methods compared", "final"),
    ("pilot_setB64_factor_effects", "PRELIMINARY — laptop pilot, 64 px, our core, 8 samples/image", "preliminary"),
]
out = ["# Results (generated by scripts/build_results_md.py — do not edit by hand)\n"]
for name, title, kind in SECTIONS:
    f = T / f"{name}.md"
    if f.exists():
        out.append(f"## {title}\n")
        if kind == "preliminary":
            out.append("> **Preliminary.** Small-scale CPU pilot used to validate the pipeline; not the final experiment.\n")
        out.append(f.read_text(encoding="utf-8").split("\n", 2)[-1] if f.read_text(encoding="utf-8").startswith("###") else f.read_text(encoding="utf-8"))
for w, title in (("f2", "F2 — are rare patches dropped?"), ("f3", "F3 — where in the pyramid does structure break?"),
                 ("f4", "F4 — effect of the two-scale blend"), ("f5", "F5 — background fraction")):
    f = FAIL / f"{w}.json"
    if f.exists():
        d = json.loads(f.read_text())
        out.append(f"## {title}\n\n> Our core on CPU, 64 px, 3 scales, {d['samples']} samples per image (laptop; preliminary).\n")
        out.append("```json\n" + json.dumps(d["result"], indent=1) + "\n```\n")
figs = sorted(FIG.rglob("*.png")) if FIG.exists() else []
if figs:
    out.append("## Figures\n")
    for p in figs[:60]:
        rel = p.relative_to(ROOT).as_posix()
        out.append(f"![{p.stem}](../{rel})\n")
(ROOT / "docs" / "results.md").write_text("\n".join(out), encoding="utf-8")
print("docs/results.md written;", len(out), "blocks")
